from uuid import UUID

from fastapi import APIRouter, HTTPException, Response, status

from app.api.deps import CurrentUser, ExerciseSvc
from app.schemas.exercise import ExerciseIn, ExerciseMerge, ExerciseMergeResult, ExerciseOut, ExerciseProgress
from app.services.errors import Conflict, Invalid, NotFound

router = APIRouter()

NOT_FOUND = HTTPException(status_code=404, detail="Exercise not found")


def _conflict(exc: Conflict) -> HTTPException:
    detail = {"message": str(exc)}
    if exc.existing_id:
        detail["existing_id"] = str(exc.existing_id)
    return HTTPException(status_code=409, detail=detail)


@router.get("/", response_model=list[ExerciseOut])
async def list_exercises(user: CurrentUser, service: ExerciseSvc) -> list[ExerciseOut]:
    """Your exercises with their last sets and records (weights compared in kg)."""
    return await service.list(user.id)


@router.get("/{exercise_id}", response_model=ExerciseOut)
async def read_exercise(exercise_id: UUID, user: CurrentUser, service: ExerciseSvc) -> ExerciseOut:
    try:
        return await service.get(user.id, exercise_id)
    except NotFound:
        raise NOT_FOUND from None


@router.put("/{exercise_id}", response_model=ExerciseOut, responses={201: {"description": "Created"}})
async def put_exercise(
    exercise_id: UUID, data: ExerciseIn, user: CurrentUser, service: ExerciseSvc, response: Response
) -> ExerciseOut:
    """Create or replace an exercise (its id is generated by the client).
    409 with `existing_id` when another exercise already has the name: merge instead."""
    try:
        exercise, created = await service.upsert(user.id, exercise_id, data)
    except NotFound:
        raise NOT_FOUND from None
    except Conflict as exc:
        raise _conflict(exc) from None
    if created:
        response.status_code = status.HTTP_201_CREATED
    return exercise


@router.delete("/{exercise_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_exercise(exercise_id: UUID, user: CurrentUser, service: ExerciseSvc) -> None:
    """Delete an exercise that no workout or plan uses. Idempotent."""
    try:
        await service.delete(user.id, exercise_id)
    except Conflict as exc:
        raise _conflict(exc) from None


@router.post("/{exercise_id}/merge", response_model=ExerciseMergeResult)
async def merge_exercise(
    exercise_id: UUID, data: ExerciseMerge, user: CurrentUser, service: ExerciseSvc
) -> ExerciseMergeResult:
    """Move this exercise's history and plan entries into another one and delete it."""
    try:
        return await service.merge(user.id, exercise_id, data.into)
    except NotFound:
        raise NOT_FOUND from None
    except Invalid as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from None


@router.get("/{exercise_id}/progress", response_model=ExerciseProgress)
async def exercise_progress(exercise_id: UUID, user: CurrentUser, service: ExerciseSvc) -> ExerciseProgress:
    """Every logged session of the exercise, oldest first."""
    try:
        return await service.progress(user.id, exercise_id)
    except NotFound:
        raise NOT_FOUND from None
