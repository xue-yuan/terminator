from datetime import UTC, datetime
from uuid import UUID, uuid4

from typing import TYPE_CHECKING

from sqlalchemy import CheckConstraint, DateTime, Float, ForeignKey, Index, String, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.exercise import Exercise


def utcnow() -> datetime:
    return datetime.now(UTC)


class Workout(Base):
    __tablename__ = "workouts"
    __table_args__ = (Index("ix_workouts_user_performed", "user_id", "performed_at"),)

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    # Public id. Generated by the client so workouts logged offline can be
    # synced idempotently (PUT /workouts/{uuid} is an upsert).
    uuid: Mapped[UUID] = mapped_column(Uuid, unique=True, default=uuid4)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    plan_day_id: Mapped[int | None] = mapped_column(
        ForeignKey("plan_days.id", ondelete="SET NULL")
    )
    name: Mapped[str | None] = mapped_column(String)
    performed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    duration_seconds: Mapped[int | None]
    notes: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, server_default=func.now()
    )

    items: Mapped[list["WorkoutItem"]] = relationship(
        back_populates="workout",
        cascade="all, delete-orphan",
        order_by="WorkoutItem.order",
        passive_deletes=True,
    )


class WorkoutItem(Base):
    """One exercise performed in a workout.

    Weights are stored as entered, in `weight_unit`, because gym equipment is
    labelled in either kg or lb.
    """

    __tablename__ = "workout_items"
    __table_args__ = (
        CheckConstraint("weight_unit IN ('kg', 'lb')", name="workout_items_weight_unit_check"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    workout_id: Mapped[int] = mapped_column(ForeignKey("workouts.id", ondelete="CASCADE"))
    exercise_id: Mapped[UUID] = mapped_column(ForeignKey("exercises.id"))
    weight_unit: Mapped[str] = mapped_column(String(2), default="kg", server_default="kg")
    # Consecutive items with the same number are a superset (done alternately).
    superset: Mapped[int | None]
    order: Mapped[int] = mapped_column(default=0, server_default="0")

    workout: Mapped[Workout] = relationship(back_populates="items")
    exercise: Mapped["Exercise"] = relationship(lazy="joined", innerjoin=True)
    sets: Mapped[list["WorkoutSet"]] = relationship(
        back_populates="item",
        cascade="all, delete-orphan",
        order_by="WorkoutSet.order",
        passive_deletes=True,
    )

    @property
    def exercise_name(self) -> str:
        return self.exercise.name


class WorkoutSet(Base):
    __tablename__ = "workout_sets"
    __table_args__ = (CheckConstraint("kind IN ('working', 'warmup')", name="workout_sets_kind_check"),)

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    item_id: Mapped[int] = mapped_column(ForeignKey("workout_items.id", ondelete="CASCADE"))
    reps: Mapped[int]
    weight: Mapped[float] = mapped_column(Float)
    rpe: Mapped[float | None] = mapped_column(Float)
    # Timed and cardio exercises (app/schemas/common.py LogType): reps are 0.
    duration_seconds: Mapped[int | None]
    distance_m: Mapped[float | None] = mapped_column(Float)
    # Warm-up sets don't count towards volume, set counts or records.
    kind: Mapped[str] = mapped_column(String(10), default="working", server_default="working")
    order: Mapped[int] = mapped_column(default=0, server_default="0")

    item: Mapped[WorkoutItem] = relationship(back_populates="sets")


Index("ix_workout_items_exercise_id", WorkoutItem.exercise_id)
Index("ix_workout_items_workout_id", WorkoutItem.workout_id)
Index("ix_workout_sets_item_id", WorkoutSet.item_id)
