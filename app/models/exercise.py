from datetime import datetime
from uuid import UUID, uuid4

from sqlalchemy import DateTime, Float, ForeignKey, Index, String, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.models.workout import utcnow


class Exercise(Base):
    """An exercise in the user's own list, e.g. "Bench Press".

    Workouts and plans refer to it by id, so renaming it is a single update and
    merging two is repointing their references. The id is generated by the
    client, so exercises created offline sync without conflicts. Names are
    unique per user, ignoring case.
    """

    __tablename__ = "exercises"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    name: Mapped[str] = mapped_column(String(100))
    muscle_group: Mapped[str | None] = mapped_column(String(20))
    # Shown while logging, e.g. seat height or grip.
    notes: Mapped[str | None] = mapped_column(Text)
    # Target rep range; drives the "add weight next time" suggestion.
    rep_min: Mapped[int | None]
    rep_max: Mapped[int | None]
    # Weight step for − / + and suggestions, in the unit the exercise is logged in.
    increment: Mapped[float | None] = mapped_column(Float)
    # Overrides the default rest timer.
    rest_seconds: Mapped[int | None]
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, server_default=func.now()
    )


Index("uq_exercises_user_name", Exercise.user_id, func.lower(Exercise.name), unique=True)
